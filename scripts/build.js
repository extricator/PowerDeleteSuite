"use strict";
const fs = require("node:fs");
const path = require("node:path");
const root = path.join(__dirname, "..");
const output = "/* Generated by npm run build; edit src/scheduler.js and src/app.js. */\n(function () {\n\"use strict\";\n" +
  ["scheduler", "app"].map(name => fs.readFileSync(path.join(root, "src", name + ".js"), "utf8")).join("\n") + "\n})();\n";
const target = path.join(root, "powerdeletesuite.js");
if (process.argv.includes("--check")) {
  if (fs.readFileSync(target, "utf8") !== output) throw new Error("Run npm run build to update powerdeletesuite.js");
} else fs.writeFileSync(target, output);
